# Generates the stack-neutral outputs of the design core into core/dist/.
# Every template reads these outputs or calls these functions; no template computes them again.
#   python3 core/build.py          write core/dist/
#   python3 core/build.py --check  fail if core/dist/ is stale
import json
import sys
from pathlib import Path

CORE = Path(__file__).parent
DIST = CORE / "dist"
read = lambda rel: (CORE / rel).read_text(encoding="utf-8")


def version():
    """The one version of the core and of every template output built from it."""
    return read("VERSION").strip()


def themes():
    return json.loads(read("tokens/themes.json"))


def theme_css(data=None):
    """One rule per theme: [data-scheme=<id>] sets color-scheme and every token as --<name>."""
    data = data or themes()
    return "\n".join(
        "[data-scheme=%s]{color-scheme:%s;%s}" % (t["id"], t["mode"], ";".join("--%s:%s" % kv for kv in t["tokens"].items()))
        for t in data["themes"])


def dictionary(data=None):
    """The language dictionary, with every theme's name and note added as entries."""
    data = data or themes()
    d = json.loads(read("i18n/i18n.json"))
    for t in data["themes"]:
        for field in ("name", "note"):
            d["text"][t[field]["zh"]] = t[field]["en"]
    return d


def gallery():
    """Gallery items as the samples read them: title, category, height/width ratio, file."""
    items = json.loads(read("content/assets/gallery/manifest.json"))["items"]
    return [{"t": m["title"], "c": m["cat"], "r": round(m["h"] / m["w"], 4), "f": m["file"]} for m in items]


def outputs():
    return {
        "tokens.css": "/* Generated by core/build.py from core/tokens/themes.json. Do not edit. */\n" + theme_css() + "\n",
        "dictionary.json": json.dumps(dictionary(), ensure_ascii=False, indent=1) + "\n",
        "gallery.json": json.dumps(gallery(), ensure_ascii=False, indent=1) + "\n",
    }


if __name__ == "__main__":
    out = outputs()
    if "--check" in sys.argv:
        stale = [n for n, v in out.items() if not (DIST / n).exists() or (DIST / n).read_text(encoding="utf-8") != v]
        if stale:
            sys.exit("core/dist is stale: %s. Run python3 core/build.py." % ", ".join(stale))
        print("core/dist is current")
    else:
        DIST.mkdir(exist_ok=True)
        for n, v in out.items():
            (DIST / n).write_text(v, encoding="utf-8")
        print("wrote", ", ".join(out))
